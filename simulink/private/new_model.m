function file = new_model(mdl, outdir, description)
%NEW_MODEL  Start a fresh model (closing and deleting an older copy) with the
%   solver settings and callbacks shared by every model of this repository.
if bdIsLoaded(mdl)
    close_system(mdl, 0);
end
file = fullfile(outdir, [mdl '.slx']);
if exist(file, 'file')
    delete(file);
end
new_system(mdl);
bm = boost_mrac_params();
init = 'if ~exist(''BM'', ''var''), boost_mrac_params; end';
set_param(mdl, ...
    'Solver', 'ode23tb', ...
    'RelTol', sprintf('%g', bm.reltol), ...
    'AbsTol', 'auto', ...
    'MaxStep', sprintf('%.10g', bm.Ts), ...
    'StopTime', '0.5', ...
    'SaveTime', 'off', ...
    'SaveOutput', 'off', ...
    'SaveState', 'off', ...
    'SaveFinalState', 'off', ...
    'SignalLogging', 'off', ...
    'ReturnWorkspaceOutputs', 'on', ...
    'AlgebraicLoopMsg', 'error', ...
    'PreLoadFcn', init, ...
    'InitFcn', init, ...
    'Description', description);
end
